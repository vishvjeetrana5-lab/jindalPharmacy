    public RptExpiryRegister(HashMap paramHashMap, SetWidgetInvoker swi) {
        super();
        flagOpenAsPopup = (Boolean) paramHashMap.get("flagOpenAsPopup");
        SrvAsync = new ServiceInvoker<>(GWT.create(RptExpiryRegister_Srv.class), RptExpiryRegister.class.getName());
        setTitle(this.asWidget(), widgetName);
        txtFromDate.addBlurHandler(this);
        txtToDate.addBlurHandler(this);
        txtHelpEvents();
        setDefaultValue();
        initialize(swi);
    }

    @Override
    public Widget asWidget() {
        if (flagOpenAsPopup) {
            return ppForm;
        } else {
            return form;
        }
    }

    private void initialize(SetWidgetInvoker swi) {

        addControl("fromDate", "From Date", vl.add(txtFromDate));
        txtFromDate.setText("");

        addControl("toDate", "To Date", vl.add(txtToDate));
        txtToDate.setText(DmClient.getLoginDate());

        iniTxtHDepartment();
        addControl("department", "Department", vl.add(txtHDepartment));

        iniTxtHSite();
        addControl("site", "Site", vl.add(txtHSite));

        iniTxtHMedGroup();
        addControl("medGroup", "Medicine Group", vl.add(txtHMedGroup));

        iniTxtHMedCat();
        addControl("medCat", "Medicine Category", vl.add(txtHMedCat));

        iniTxtHMedicine();
        addControl("medicine", "Medicine", vl.add(txtHMedicine));

        iniTxtHBatchNo();
        addControl("batchNo", "Batch No.", vl.add(txtHBatchNo));

        iniTxtHValueOn();
        addControl("valueOn", "Value On", vl.add(txtHValueOn));

        iniTxtHGroupBy();
        addControl("groupBy", "Group By", vl.add(txtHGroupBy));

        iniTxtHYesNo();
        addControl("purchaseDetail", "Purchase Detail", vl.add(txtHYesNo));

        initxtHMedCompany();
        addControl("medCompany", "Medicine Company", vl.add(txtHMedCompany));

        if (flagOpenAsPopup) {
            ppForm.clear();
            form.getElement().setAttribute("Style", "width:980px; height:500px;");

            Element e = form.getElement().getElementsByTagName("iframe").getItem(0);
            e.getStyle().setWidth(980, Style.Unit.PX);
            e.getStyle().setHeight(474, Style.Unit.PX);
            ppForm.add(form);
            ppForm.setGlassEnabled(true);
            ppForm.center();

            onView();
        }

        swi.setWidget(this);

    }

    private void setDefaultValue() {
        txtHValueOn.setTag("L");
        txtHValueOn.setText("Landed Rate");
        txtHGroupBy.setTag("Medicine Category");
        txtHGroupBy.setText("Medicine Category");
        txtHYesNo.setTag("0");
        txtHYesNo.setText("No");
        setDefaultSite();
    }

    private void setDefaultSite() {
        SrvAsync.invokeRPC().getDefaultValue(new AsyncCallback<DmResult<KeyFieldExtended>>() {
            @Override
            public void onFailure(Throwable caught) {
                new DmAlertMessageBox(caught.getMessage(), (DmTextBox) null).show();
            }

            @Override
            public void onSuccess(DmResult<KeyFieldExtended> result) {
                if (result.isStatus()) {
                    KeyFieldExtended keyField = result.getData();
                    txtHSite.setTag(keyField.getSharedKeyFieldCode());
                    txtHSite.setText(keyField.getSharedKeyFieldName());
                } else {
                    new DmAlertMessageBox(result.getErrorMessage(), (DmTextBox) null).show();
                }
            }
        });
    }

