    @Override
    public DmResult<KeyFieldExtended> execute(String sessionId, LinkedHashMap<String, FieldUDT_Mdl> filter, DmReportProperty_Mdl reportProperty, String widgetName) {
        DmResult<KeyFieldExtended> rstTemp = new DmResult<>();
        Connection cnTemp = null;
        DmPreparedStatement psTemp = null;
        ResultSet rsTemp = null;
        JasperReport jasperReport;
        JasperPrint jasperPrint;
        String sqlQuery;
        String condition = " ";
        KeyFieldExtended keyField = new KeyFieldExtended();
        FileWriter fileWriter = null;
        String fileName = widgetName.replaceAll(" ", "");
        String COMMA_DELIMITER = ",", NEW_LINE_SEPARATOR = System.lineSeparator(), lineData = "";

        try {
            RptIndentEntryRegister_Vld.validateInput(filter);
            cnTemp = DmServer.getConnection(DmServer.getSsnDBName(this));

            if (!DmShared.xNull(filter.get("fromDate").getText()).trim().equalsIgnoreCase("")) {
                condition += " and  i.v_Date >= :fromDate ";
            }
            if (!DmShared.xNull(filter.get("toDate").getText()).trim().equalsIgnoreCase("")) {
                condition += " and  i.v_Date <= :toDate ";
            }
            if (!DmShared.xNull(filter.get("department").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and i.departmentCode in (" + DmServer.getParamList(":departmentCode", filter.get("department").getTag()) + " )";
            }
            if (!DmShared.xNull(filter.get("indentNo").getTag()).trim().equalsIgnoreCase("")) {
                condition += " AND i.docId IN (" + DmServer.getParamList(":indentNo", filter.get("indentNo").getTag()) + " )";
            }
            if (!DmShared.xNull(filter.get("indentor").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and i.indentorCode in (" + DmServer.getParamList(":indentorCode", filter.get("indentor").getTag()) + " )";
            }
            if (!DmShared.xNull(filter.get("indentType").getTag()).trim().equalsIgnoreCase("")) {
                condition += " AND  vt.v_Type IN (" + DmServer.getParamList(":v_Type", filter.get("indentType").getTag()) + " ) ";
            }
            if (!DmShared.xNull(filter.get("requisitionNo").getTag()).trim().equalsIgnoreCase("")) {
                condition += " AND rq.docId IN (" + DmServer.getParamList(":requisitionNo", filter.get("requisitionNo").getTag()) + " )";
            }
            if (!DmShared.xNull(filter.get("Status").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and ind.isStatus = :isStatus ";
            }
            if (!DmShared.xNull(filter.get("medGroup").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and im.itemGroup  in (" + DmServer.getParamList(":medGroup ", filter.get("medGroup").getTag()) + " )";
            }
            if (!DmShared.xNull(filter.get("medCategory").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and im.itemCategoryCode  in (" + DmServer.getParamList(":medCategoryCode ", filter.get("medCategory").getTag()) + " )";
            }
            if (!DmShared.xNull(filter.get("medName").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and ind.itemCode  in (" + DmServer.getParamList(":medCode ", filter.get("medName").getTag()) + " )";
            }
            if (!DmShared.xNull(filter.get("site").getTag()).trim().equalsIgnoreCase("")) {
                condition += " AND   i.site_Code IN (" + DmServer.getParamList(":site_Code ", filter.get("site").getTag()) + " )";
            }
            if (!DmShared.xNull(filter.get("medCompany").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and im.itemMakeCode in (" + DmServer.getParamList(":medCompany", filter.get("medCompany").getTag()) + " )";
            }

            if (reportProperty.getExportType() == DmEnum.DmExportType.EXCEL) {
                String directoryPath = DmServer.Path.sessions + "/" + sessionId;
                String serverFileName = fileName + ".csv";
                String fullFilePath = directoryPath + "/" + serverFileName;

                File sFile = new File(directoryPath);
                if (!sFile.exists()) {
                    sFile.mkdirs();
                }
                File nFile = new File(fullFilePath);
                if (nFile.exists()) {
                    nFile.delete();
                }

                keyField.setSharedKeyFieldCode(directoryPath);
                keyField.setSharedKeyFieldName(serverFileName);
                fileWriter = new FileWriter(fullFilePath, true);
            }

            sqlQuery = " SELECT  i.docId,vt.short_Name AS shortName, i.recId AS indNo, i.v_Date,sdm.name AS depName,"
                    + "  sg.name as indentorName,"
                    + "  imm.companyName AS companyName ,\n"
                      + "  im.itemMakeCode AS companyCode, \n"
                    + "          im.name AS itemName, ind.reqQty,ind.aprQty,ind.orderedQty, um.unit, ind.reqDate,  "
                    + "          format(i.approvalDateTime, 'dd-MMM-yyyy / HH:mm') as approvalDateTime, "
                    + "          CASE when ind.isStatus ='2' then 'Completed' when ind.isStatus ='1' then 'Cancelled' when isNull(ind.isStatus,'0')='0' then 'Open' end AS isStatus , "
                    + "          Cast(IsNull(ind.aprQty,0)-(IsNull(ind.orderedQty,0)) as decimal(18,7)) as pendingQuantity ,rq.recId as requisitionNo,"
                    + "          isNull(isNull(ind.aprQty,0) * isNull(im.purchaseRate,0),0) as EstimatedVal,ind.statusRemark   "
                    + "          FROM indent i   "
                    + "          LEFT JOIN indentDetail AS ind ON ind.docId=i.docId    "
                    + "          LEFT JOIN subgroup sdm ON i.departmentCode = sdm.subcode     "
                    + "          LEFT JOIN subgroup sg ON i.indentorCode = sg.subCode    "
                    + "          LEFT JOIN voucher_type vt ON i.v_Type = vt.v_Type    "
                    + "          LEFT JOIN itemMast AS im ON im.code=ind.itemCode  "
                    + "          LEFT JOIN itemmakemast imm ON imm.code = im.itemMakeCode\n"
                    + "          LEFT JOIN itemGroup ig ON ig.code = im.itemGroup    "
                    + "          LEFT JOIN itemCat ic ON ic.code = im.itemCategoryCode  "
                    + "          LEFT JOIN unitMast um ON um.code = im.sku   "
                    + "          LEFT JOIN requisition rq ON rq.docId =ind.requisitionDocId "
                    + "          LEFT JOIN medicineCompoMast mcm ON mcm.code=im.compositionCode  "
                    + "          WHERE vt.category = '" + v_TypeShortName + "'" + condition
                    + "          AND ISNULL(i.approvedBy, '') <> ''"
                    + "          ORDER BY i.v_Date , vt.short_Name , i.v_No,i.recId, ind.v_SNo";
            psTemp = DmPreparedStatement.prepareStatement(cnTemp, sqlQuery);
            getParameter(filter, psTemp);
            rsTemp = psTemp.executeQuery();

            if (reportProperty.getExportType() == DmEnum.DmExportType.EXCEL) {

                String FILE_HEADER = "Indent No.,Type,Date,Indentor Name,Department,Requisition No.,Medicine Name,Medicine Company,Sku,Ind Qty,"
                        + "Apr. Qty,Ord. Qty,Pnd. Qty, Req. Date,Status,Status Remark";

                fileWriter.append(FILE_HEADER.toString());
                fileWriter.append(NEW_LINE_SEPARATOR);

                while (rsTemp.next()) {

                    lineData = DmShared.xNull(rsTemp.getString("indNo")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("shortName")) + COMMA_DELIMITER;
                    lineData += DmShared.dNull(rsTemp.getDate("v_Date")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("indentorName")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("depName")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("requisitionNo")) + COMMA_DELIMITER;

                    lineData += DmShared.xNull(rsTemp.getString("itemName")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("companyName")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("unit")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("reqQty")) + COMMA_DELIMITER;
                    lineData += DmServer.vNull(rsTemp.getString("aprQty")) + COMMA_DELIMITER;
                    lineData += DmServer.vNull(rsTemp.getString("orderedQty")) + COMMA_DELIMITER;
                    lineData += DmServer.vNull(rsTemp.getString("pendingQuantity")) + COMMA_DELIMITER;

                    lineData += DmShared.dNull(rsTemp.getDate("reqDate")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("isStatus")) + COMMA_DELIMITER;
                    lineData += DmShared.xNull(rsTemp.getString("statusRemark")) + COMMA_DELIMITER;

                    fileWriter.append(lineData);
                    fileWriter.append(NEW_LINE_SEPARATOR);

                }

                fileWriter.flush();
                fileWriter.close();
            }

            if (reportProperty.getExportType() == DmEnum.DmExportType.PDF) {
                jasperReport = DmServer.compileJasper("Pharmacy_IndentRegister");
                jasperPrint = DmServer.fillJasper(this, "Indent Register", jasperReport, null, filter, rsTemp);
                keyField.setSharedKeyFieldName(DmServer.showJasper(this, jasperPrint, "", reportProperty));

            }
            rstTemp.setData(keyField);
            rstTemp.setStatus(true);
        } catch (Exception e) {
            rstTemp.setStatus(false);
            rstTemp.setErrorMessage(e.getMessage());
        } finally {
            try {
                if (rsTemp != null) {
                    rsTemp.close();
                }
                if (psTemp != null) {
                    psTemp.close();
                }
                if (cnTemp != null && !cnTemp.isClosed()) {
                    cnTemp.close();
                }
            } catch (Exception e) {
            }
        }
        return rstTemp;
    }

