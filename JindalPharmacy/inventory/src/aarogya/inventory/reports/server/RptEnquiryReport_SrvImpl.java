    @Override
    public DmResult<String> execute(LinkedHashMap<String, FieldUDT_Mdl> filter, DmReportProperty_Mdl reportProperty) {
        DmResult<String> rstTemp = new DmResult<>();
        Connection cnTemp = null;
        DmPreparedStatement psTemp = null;
        ResultSet rsTemp = null;
        JasperReport jasperReport;
        JasperPrint jasperPrint;
        String sqlQuery = "", condition = " ", conditionSupplier = " ", joinIndent = "", joinSupplier = "";

        try {
            RptEnquiryReport_Vld.validateInput(filter);
            cnTemp = DmServer.getConnection(DmServer.getSsnDBName(this));

            if (!DmShared.xNull(filter.get("fromDate").getText()).trim().equalsIgnoreCase("")) {
                condition += " and  enq.v_Date >= :fromDate ";

            }
            if (!DmShared.xNull(filter.get("toDate").getText()).trim().equalsIgnoreCase("")) {
                condition += " and  enq.v_Date <= :toDate ";

            }
            if (!DmShared.xNull(filter.get("enquiryType").getTag()).trim().equalsIgnoreCase("")) {
                condition += " AND  enq.v_Type IN (" + DmServer.getParamList(":v_Type", filter.get("enquiryType").getTag()) + " ) ";

            }
            if (!DmShared.xNull(filter.get("enquiryno").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and enq.docId in (" + DmServer.getParamList(":docId", filter.get("enquiryno").getTag()) + " )";

            }

            if (!DmShared.xNull(filter.get("supplier").getTag()).trim().equalsIgnoreCase("")) {
                conditionSupplier = " AND evd.subCode in (" + DmServer.getParamList(":subCode", filter.get("supplier").getTag()) + " ) ";

                joinSupplier = "INNER JOIN ("
                        + "             SELECT evd.docId "
                        + "             FROM enquiryVendorDetail evd "
                        + "             WHERE evd.subCode in (" + DmServer.getParamList(":subCode", filter.get("supplier").getTag()) + " ) "
                        + "             GROUP BY evd.docid"
                        + "             ) vEvd ON vEvd.docid = enq.docid  ";
            }

            if (!DmShared.xNull(filter.get("item").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and ed.itemCode in (" + DmServer.getParamList(":itemCode", filter.get("item").getTag()) + " )";

            }
            if (!DmShared.xNull(filter.get("itemGroup").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and im.itemGroup in (" + DmServer.getParamList(":itemGroup", filter.get("itemGroup").getTag()) + " )";

            }
            if (!DmShared.xNull(filter.get("itemCat").getTag()).trim().equalsIgnoreCase("")) {
                condition += " and im.itemCategoryCode in (" + DmServer.getParamList(":itemCat", filter.get("itemCat").getTag()) + " )";

            }
            if (!DmShared.xNull(filter.get("indent").getTag()).trim().equalsIgnoreCase("")) {
                joinIndent = "INNER JOIN ("
                        + "         SELECT eid.docId, eid.v_SNo "
                        + "         FROM enquiryIndentDetail eid "
                        + "         WHERE eid.indentDocid in (" + DmServer.getParamList(":indent", filter.get("indent").getTag()) + " ) "
                        + "         GROUP BY eid.docId, eid.v_SNo "
                        + "         ) vEid ON vEid.docid = ed.docid AND vEid.v_SNo = ed.v_SNo ";

            }
            if (!DmShared.xNull(filter.get("site").getTag()).trim().equalsIgnoreCase("")) {
                condition += " AND   enq.site_Code IN (" + DmServer.getParamList(":site_Code ", filter.get("site").getTag()) + " )";
            }
            sqlQuery = " SELECT  enq.docId, ed.v_SNo, enq.v_Type, vt.short_Name, enq.recId AS enqNo, enq.v_Date AS enqDate, enq.referenceNo, "
                    + "		im.name AS itemName, ed.quantity, um.unit AS unitName, ed.scheduleDate, ed.remark,"
                    + "         enq.site_Code, sm.name as siteName,"
                    + "         ed.colourCode,icm.name as colourName,ed.sizeCode,ism.name as sizeName,ev.supplierName "
                    + "		FROM enquiry enq  "
                    + "" + joinSupplier
                    + "		LEFT JOIN enquiryDetail ed ON ed.docId = enq.docId  "
                    + "" + joinIndent
                    + "		LEFT JOIN voucher_type vt ON enq.v_Type = vt.v_Type  "
                    + "		LEFT JOIN itemMast im ON im.code = ed.itemCode  "
                    + "		LEFT JOIN unitMast um ON um.code = im.purchaseUnit  "
                    + "		LEFT JOIN itemCat ic ON im.itemCategoryCode = ic.code  "
                    + "         LEFT JOIN siteMast sm ON sm.code = enq.site_Code  	"
                    + " 	LEFT JOIN itemColourMast icm ON icm.code=ed.colourCode "
                    + "		LEFT JOIN itemSizeMast ism ON ism.code=ed.sizeCode "
                    + "         CROSS APPLY ( "
                    + "           SELECT STUFF((SELECT char(10) +CASE WHEN isNull(c.cityName,'') <>''  THEN sg.name +', '+c.cityName ELSE sg.name END  AS [text()]"
                    + "           FROM enquiryVendorDetail evd "
                    + "           LEFT JOIN subGroup sg ON sg.subCode = evd.subCode "
                    + "           left join city as c on c.cityCode = sg.cityCode           "
                    + "           WHERE evd.docid = enq.docid " + conditionSupplier
                    + "           FOR XML PATH('')), 1,1, '') "
                    + "          ) ev(supplierName)"
                    + "		WHERE vt.category = " + vCat + condition
                    + "         AND ISNULL(enq.approvedBy, '') <> ''"
                    + "		ORDER BY enq.v_Date, vt.short_Name, enq.v_No,enq.recId, ed.v_SNo ";

            psTemp = DmPreparedStatement.prepareStatement(cnTemp, sqlQuery);
            getParameter(filter, psTemp);
            rsTemp = psTemp.executeQuery();

            jasperReport = DmServer.compileJasper("Inventory_EnquiryRegister");
            jasperPrint = DmServer.fillJasper(this, " Enquiry Register", jasperReport, null, filter, rsTemp);

            rstTemp.setData(DmServer.showJasper(this, jasperPrint, "", reportProperty));
            rstTemp.setStatus(true);
        } catch (Exception e) {
            rstTemp.setStatus(false);
            rstTemp.setErrorMessage(e.getMessage());
        } finally {
            try {
                if (rsTemp != null) {
                    rsTemp.close();
                }
                if (psTemp != null) {
                    psTemp.close();
                }
                if (cnTemp != null && !cnTemp.isClosed()) {
                    cnTemp.close();
                }
            } catch (Exception e) {
            }
        }
        return rstTemp;
    }

