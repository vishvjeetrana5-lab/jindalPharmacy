    private void initGrid() {
        try {
            Dimension dim = Toolkit.getDefaultToolkit().getScreenSize();
            setLocation(dim.width / 2 - this.getSize().width / 2, dim.height / 2 - this.getSize().height / 2);

            resultsTable.setModel(new DefaultTableModel() {

                @Override
                public int getColumnCount() {
                    return columnNames.length;
                }

                @Override
                public String getColumnName(int column) {
                    return columnNames[column];
                }

                @Override
                public int getRowCount() {
                    return listStartupResults.size();
                }

                @Override
                public String getValueAt(int row, int column) {
                    String cellValue = "";
                    if (column == 0) {
                        cellValue = listStartupResults.get(row).getManualMachineCode();
                    } else if (column == 1) {
                        cellValue = listStartupResults.get(row).getMachineCode();
                    } else if (column == 2) {
                        cellValue = listStartupResults.get(row).getMachineStartupResult();
                    }
                    return cellValue;
                }

                @Override
                public boolean isCellEditable(int row, int column) {
                    return false;
                }

            });

            resultsTable.setShowGrid(true);
            for (int i = 0; i < columnNames.length; i++) {
                WordWrapCellRenderer cellRenderer = new WordWrapCellRenderer();
                cellRenderer.setAlignmentY(JTextArea.LEFT_ALIGNMENT);
                cellRenderer.setAlignmentX(JTextArea.CENTER_ALIGNMENT);
                resultsTable.getColumnModel().getColumn(i).setCellRenderer(cellRenderer);

                DefaultTableCellRenderer cellHeaderRenderer = new DefaultTableCellRenderer();
                cellHeaderRenderer.setHorizontalAlignment(JLabel.LEFT);
                cellHeaderRenderer.setBackground(Color.lightGray);
                cellHeaderRenderer.setFont(new Font(resultsTable.getFont().getName(), Font.BOLD, resultsTable.getFont().getSize()));
                resultsTable.getColumnModel().getColumn(i).setHeaderRenderer(cellHeaderRenderer);
            }
        } catch (Exception ex) {
            new JOptionPane(ex.getMessage(), JOptionPane.ERROR, JOptionPane.OK_OPTION).show();
        } finally {
            pack();
        }
    }

