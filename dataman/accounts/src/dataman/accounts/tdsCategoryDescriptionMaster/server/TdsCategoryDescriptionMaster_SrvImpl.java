    @Override
    public DmResult<String> saveRecord(TdsCategoryDescriptionMaster_Mdl mrTemp) {
        DmResult<String> dmrTemp = new DmResult();
        Connection cnTemp = null;
        DmPreparedStatement psTemp = null;
        DmSavePoint spBegin = null;
        boolean blnAdd = false;
        String strSQL;
        ResultSet rsTemp = null;
        dmrTemp.setData("");

        try {
            TdsCategoryDescriptionMaster_Vld.chkSave(mrTemp);

            cnTemp = DmServer.getConnection(DmServer.getSsnDBName(this));
            spBegin = new DmSavePoint(cnTemp);

            mrTemp.setSharedKeyFieldName(DmShared.removeSpace(mrTemp.getSharedKeyFieldName()));

            //================================<< GENERATE NEW CODE IF BLANK >>===============================
            if (DmShared.xNull(mrTemp.getSharedKeyFieldCode()).equalsIgnoreCase("")) {
                blnAdd = true;
                mrTemp.setSharedKeyFieldCode(DmServer.getSerialNoInteger(this, "tdsCat_Description", cnTemp));
            }

            if (mrTemp.getSharedKeyFieldCode().equalsIgnoreCase("")) {
                throw new UnsupportedOperationException("Invalid key.");
            }
            //========================================<< END >>=====================================================

            //================================<< CHECK DUPLICATE FOR TDS DESCRIPTION >>============================
            strSQL = "Select Count(name) As Cnt From tdsCat_Description Where LOWER(name) = :name And code <> :code ";
            psTemp = DmPreparedStatement.prepareStatement(cnTemp, strSQL);
            psTemp.setString("name", mrTemp.getSharedKeyFieldName());
            psTemp.setString("code", mrTemp.getSharedKeyFieldCode());
            rsTemp = psTemp.executeQuery();
            rsTemp.next();
            if (rsTemp.getLong("cnt") > 0) {
                throw new UnsupportedOperationException("TDS Description already exists.");
            }
            rsTemp.close();
            psTemp.close();
            //========================================<< END >>=====================================================

            //================================<< CHECK DUPLICATE FOR MANUAL CODE >>================================
            strSQL = "Select Count(manualCode) As Cnt From tdsCat_Description Where LOWER(manualCode) = :manualCode And code <> :code ";
            psTemp = DmPreparedStatement.prepareStatement(cnTemp, strSQL);
            psTemp.setString("manualCode", mrTemp.getManualCode());
            psTemp.setString("code", mrTemp.getSharedKeyFieldCode());
            rsTemp = psTemp.executeQuery();
            rsTemp.next();
            if (rsTemp.getLong("cnt") > 0) {
                throw new UnsupportedOperationException("Manual Code already exists.");
            }
            rsTemp.close();
            psTemp.close();
            //========================================<< END >>=====================================================

            //================================<< INSERT INTO TDS DESCRIPTION TABLE >>================================
            if (blnAdd) {
                strSQL = "Insert Into tdsCat_Description(code,name,manualCode, "
                        + " preparedBY,U_EntDt) Values  "
                        + "(:code,:name,:manualCode,:preparedBY,getdate()) ";
                psTemp = DmPreparedStatement.prepareStatement(cnTemp, strSQL);
                psTemp.setString("code", DmShared.iNull(mrTemp.getSharedKeyFieldCode()).toString());
                psTemp.setString("name", DmShared.xNull(mrTemp.getSharedKeyFieldName()));
                psTemp.setString("manualCode", DmShared.xNull(mrTemp.getManualCode()));
                psTemp.setString("preparedBY", DmServer.getSsnUserName(this));

            } else {
                strSQL = "Update tdsCat_Description Set "
                        + "name = :name, "
                        + "manualCode = :manualCode, "
                        + "transferDt = :transferDt, "
                        + "U_Name = :u_name, "
                        + "U_EntDt = getdate() "
                        + "Where code = :code ";
                psTemp = DmPreparedStatement.prepareStatement(cnTemp, strSQL);
                psTemp.setString("name", DmShared.xNull(mrTemp.getSharedKeyFieldName()));
                psTemp.setString("manualCode", DmShared.xNull(mrTemp.getManualCode()));
                psTemp.setString("transferDt", null);
                psTemp.setString("u_name", DmServer.getSsnUserName(this));
                psTemp.setString("code", mrTemp.getSharedKeyFieldCode());
            }
            psTemp.executeUpdate();
            psTemp.close();

            dmrTemp.setData(mrTemp.getSharedKeyFieldCode());
            spBegin.commit();
            cnTemp.close();
            dmrTemp.setStatus(true);
        } catch (Exception e) {
            try {
                if (spBegin != null) {
                    spBegin.rollBack();
                }
            } catch (Exception ex) {
            }
            dmrTemp.setErrorMessage(DmShared.xNull(e.getMessage()));
        } finally {
            try {
                if (rsTemp != null) {
                    rsTemp.close();
                }

                if (psTemp != null) {
                    psTemp.close();
                }

                if (cnTemp != null && !cnTemp.isClosed()) {
                    cnTemp.close();
                }
            } catch (Exception e) {
            }
        }

        return dmrTemp;
    }

