    @Override
    public DmResult<String> execute(LinkedHashMap<String, FieldUDT_Mdl> filter, DmReportProperty_Mdl reportProperty) {
        DmResult<String> rstTemp = new DmResult<>();
        Connection cnTemp = null;
        DmPreparedStatement psTemp = null;
        ResultSet rsTemp = null;
        JasperReport jasperReport;
        JasperPrint jasperPrint;
        String strCondition1, strSQLQuery;

        try {
            TDSCertificate_Model.validateInput(filter);
            cnTemp = DmServer.getConnection(DmServer.getSsnDBName(this));

            strCondition1 = " And (L.V_Date Between :fromDate And :toDate) ";

            if (!DmShared.xNull(filter.get("categoryName").getTag()).trim().equalsIgnoreCase("")) {
                strCondition1 = strCondition1 + "  And TC.Code In (" + DmServer.getParamList(":categoryName", DmShared.xNull(filter.get("categoryName").getTag())) + ") ";
            }

            if (!DmShared.xNull(filter.get("siteName").getTag()).trim().equalsIgnoreCase("")) {
                strCondition1 = strCondition1 + " And L.Site_Code In (" + DmServer.getParamList(":siteName", DmShared.xNull(filter.get("siteName").getTag())) + ") ";
            } else {
                strCondition1 = strCondition1 + " And L.Site_Code In  (" + DmServer.getParamList(":siteName", DmShared.xNull(DmServer.getSsnSiteList(this))) + ") ";
            }

            strSQLQuery = "SELECT TC.Name AS TSDCat,Sum(L.TdsOnAmt) AS TdsOnAmt, ";
            strSQLQuery += "Sum(Case When isNull(L.AmtCr,0)>0 Then isNull(L.AmtCr,0) Else 0 - isNull(L.AmtDr,0) END) As TdsAmt ";
            strSQLQuery += "FROM Ledger L ";
            strSQLQuery += "LEFT JOIN SubGroup SG ON SG.SubCode =L.ContraSub ";
            strSQLQuery += "LEFT JOIN TDSCat TC ON TC.Code=L.TDSCategory ";
            strSQLQuery += "WHERE isNull(L.TDSCategory,'')<>'' AND isNull(L.tdsdesc,'')<>'' ";
            strSQLQuery += "AND L.isSystem_Generated ='1' ";
            strSQLQuery += strCondition1 + " GROUP BY TC.Name ";

            psTemp = DmPreparedStatement.prepareStatement(cnTemp, strSQLQuery);
            psTemp.setDate("fromDate", DmServer.convertDate(filter.get("fromDate").getText()), true);
            psTemp.setDate("toDate", DmServer.convertDate(filter.get("toDate").getText()), true);

            if (!DmShared.xNull(filter.get("categoryName").getTag()).trim().equalsIgnoreCase("")) {
                psTemp.setStringList("categoryName", DmShared.xNull(filter.get("categoryName").getTag()), true);
            }

            if (!DmShared.xNull(filter.get("siteName").getTag()).trim().equalsIgnoreCase("")) {
                psTemp.setStringList("siteName", DmShared.xNull(filter.get("siteName").getTag()));
            } else {
                psTemp.setStringList("siteName", DmShared.xNull(DmServer.getSsnSiteList(this)));
            }

            rsTemp = psTemp.executeQuery();

            jasperReport = DmServer.compileJasper("AC_TDSTaxChallan");
            jasperPrint = DmServer.fillJasper(this, "TDS Certificate", jasperReport, new HashMap(), filter, rsTemp);
            rstTemp.setData(DmServer.showJasper(this, jasperPrint, "", reportProperty));
            rstTemp.setStatus(true);
        } catch (Exception e) {
            rstTemp.setStatus(false);
            rstTemp.setErrorMessage(e.getMessage());
        } finally {
            try {
                if (rsTemp != null) {
                    rsTemp.close();
                }
                if (psTemp != null) {
                    psTemp.close();
                }
                if (cnTemp != null && !cnTemp.isClosed()) {
                    cnTemp.close();
                }
            } catch (Exception e) {
            }
        }
        return rstTemp;
    }
