    @Override
    public DmResult<String> saveRecord(StateMaster_Mdl mrTemp) {
        DmResult<String> dmrTemp = new DmResult();
        Connection cnTemp = null;
        DmPreparedStatement psTemp = null;
        DmSavePoint spBegin = null;
        boolean blnAdd = false;
        String sqlQuery;
        ResultSet rsTemp = null;
        dmrTemp.setData("");

        try {
            mrTemp.setNumericCode(DmShared.xNull(mrTemp.getNumericCode()).replace(" ", "").trim());
            mrTemp.setTextCode(DmShared.xNull(mrTemp.getTextCode()).replace(" ", "").trim());
            StateMaster_Vld.chkSave(mrTemp);

            cnTemp = DmServer.getConnection(DmServer.getSsnDBName(this));
            spBegin = new DmSavePoint(cnTemp);

            mrTemp.setSharedKeyFieldName(DmShared.removeSpace(mrTemp.getSharedKeyFieldName()));
            if (DmShared.xNull(mrTemp.getSharedKeyFieldCode()).equalsIgnoreCase("")) {
                blnAdd = true;
                mrTemp.setSharedKeyFieldCode(DmServer.getSerialNoInteger(this, "stateMast", cnTemp));
            }

            if (mrTemp.getSharedKeyFieldCode().equalsIgnoreCase("")) {
                throw new UnsupportedOperationException("Invalid key.");
            }

            /*=======================< Check whether Name already exist or not >======================*/
            sqlQuery = "select code from stateMast where name = :name and code <> :code ";
            psTemp = DmPreparedStatement.prepareStatement(cnTemp, sqlQuery);
            psTemp.setString("name", DmShared.xNull(mrTemp.getSharedKeyFieldName()));
            psTemp.setString("code", DmShared.xNull(mrTemp.getSharedKeyFieldCode()));
            rsTemp = psTemp.executeQuery();
            if (rsTemp.next()) {
                throw new DmException(100, "Name already exists.");
            }
            rsTemp.close();
            psTemp.close();

            /*=======================< Check whether Numeric Code already exist or not >======================*/
            sqlQuery = "select code from stateMast where numericCode = :numericCode and code <> :code ";
            psTemp = DmPreparedStatement.prepareStatement(cnTemp, sqlQuery);
            psTemp.setString("code", DmShared.xNull(mrTemp.getSharedKeyFieldCode()));
            psTemp.setString("numericCode", DmServer.vNull(mrTemp.getNumericCode(), "00"));
            rsTemp = psTemp.executeQuery();
            if (rsTemp.next()) {
                throw new DmException(100, "Numeric Code already exists.");
            }
            rsTemp.close();
            psTemp.close();

            /*=======================< Check whether Text Code already exist or not >======================*/
            sqlQuery = "select code from stateMast where textCode = :textCode and code <> :code ";
            psTemp = DmPreparedStatement.prepareStatement(cnTemp, sqlQuery);
            psTemp.setString("textCode", DmShared.xNull(mrTemp.getTextCode()));
            psTemp.setString("code", DmShared.xNull(mrTemp.getSharedKeyFieldCode()));
            rsTemp = psTemp.executeQuery();
            if (rsTemp.next()) {
                throw new DmException(100, "Text Code already exists.");
            }
            rsTemp.close();
            psTemp.close();

            /*===============================< Insert/Update record into stateMast >==============================*/
            if (blnAdd) {
                sqlQuery = "Insert Into stateMast(code, name, numericCode, textCode, isUT, preparedBy, u_EntDt) "
                        + " Values (:code, :name, :numericCode, :textCode, :isUT, :preparedBy, GETDATE()) ";
                psTemp = DmPreparedStatement.prepareStatement(cnTemp, sqlQuery);
                psTemp.setString("code", DmShared.iNull(mrTemp.getSharedKeyFieldCode()).toString());
                psTemp.setString("name", DmShared.xNull(mrTemp.getSharedKeyFieldName()));
                psTemp.setString("numericCode", DmServer.vNull(mrTemp.getNumericCode(), "00"));
                psTemp.setString("textCode", DmShared.xNull(mrTemp.getTextCode()));
                psTemp.setString("isUT", DmShared.xNull(mrTemp.getUtCode()));
                psTemp.setString("preparedBy", DmServer.getSsnUserName(this));
            } else {
                sqlQuery = "Update stateMast Set "
                        + " name = :name, "
                        + " numericCode = :numericCode, "
                        + " textCode = :textCode, "
                        + " isUT = :isUT, "
                        + " u_Name = :u_Name, "
                        + " u_EntDt = GETDATE() "
                        + " Where code = :code ";
                psTemp = DmPreparedStatement.prepareStatement(cnTemp, sqlQuery);
                psTemp.setString("code", DmShared.iNull(mrTemp.getSharedKeyFieldCode()).toString());
                psTemp.setString("name", DmShared.xNull(mrTemp.getSharedKeyFieldName()));
                psTemp.setString("numericCode", DmServer.vNull(mrTemp.getNumericCode(), "00"));
                psTemp.setString("textCode", DmShared.xNull(mrTemp.getTextCode()));
                psTemp.setString("u_Name", DmServer.getSsnUserName(this));
                psTemp.setString("isUT", DmShared.xNull(mrTemp.getUtCode()));
            }
            psTemp.executeUpdate();
            psTemp.close();

            dmrTemp.setData(mrTemp.getSharedKeyFieldCode());
            spBegin.commit();
            cnTemp.close();
            dmrTemp.setStatus(true);
        } catch (Exception e) {
            try {
                if (spBegin != null) {
                    spBegin.rollBack();
                }
            } catch (Exception ex) {
            }
            if (e instanceof DmException) {
                dmrTemp.setErrorNumber(((DmException) e).getErrorNo());
            }
            dmrTemp.setErrorMessage(DmShared.xNull(e.getMessage()));
        } finally {
            try {
                if (rsTemp != null) {
                    rsTemp.close();
                }
                if (psTemp != null) {
                    psTemp.close();
                }
                if (cnTemp != null && !cnTemp.isClosed()) {
                    cnTemp.close();
                }
            } catch (Exception e) {
            }
        }

        return dmrTemp;
    }

