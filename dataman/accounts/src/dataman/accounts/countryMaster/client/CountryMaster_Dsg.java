abstract class CountryMaster_Dsg extends IsWidgetExtended {

     final  String widgetName = new lmAccounts().COUNTRY_MASTER.caption;
    public final static String preparedByBlog = "Prepared By";
    public final static String modifiedByBlog = "Modified By";

    final DmClient.ViaList vl = new DmClient.ViaList();
    final FlowPanel flwForm = new FlowPanel();
    final DmUserControl userControl = new DmUserControl();
    final VerticalPanel vrtInnerForm = new VerticalPanel();
    final DmTopControl topControl = new DmTopControl(vl, userControl);
    final DmSuggestBox txtCountryName = new DmSuggestBox(0, 10, false, "Name", DmDataType.STRING);

    //<editor-fold defaultstate="collapsed" desc="txtHCurrency">
    final DmTextHelp<KeyFieldExtended, KeyField_PrpAcs> txtHCurrency = new DmTextHelp(GWT.create(KeyField_PrpAcs.class), 7);

    public void iniCurrency() {
        txtHCurrency.getDmGrid().addTextColumn(txtHCurrency.getDmGrid().getPropertyAccess().name(), "Name", 0, "Name");
        txtHCurrency.getDmGrid().initializeGrid(txtHCurrency.getDmGrid().getPropertyAccess().code(), 200, 0, 1);
        txtHCurrency.getHelper().addSort("Name", DmSortType.ASC);
    }
//</editor-fold>

    //<editor-fold defaultstate="collapsed" desc="dmFind">
    interface DmFind_PrpAcs extends KeyField_T_PrpAcs<Find_Mdl> {

        @Editor.Path("CurrencyName")
        ValueProvider<Find_Mdl, String> currencyName();

    }
    final DmFind<Find_Mdl, DmFind_PrpAcs> dmFind = new DmFind(GWT.create(DmFind_PrpAcs.class), 7);

    public void iniFind() {
        dmFind.getDmGrid().addTextColumn(dmFind.getDmGrid().getPropertyAccess().name(), "Country Name", 0, "Name");
        dmFind.getDmGrid().addTextColumn(dmFind.getDmGrid().getPropertyAccess().currencyName(), "Currency Name", 200, "Currency");
        dmFind.getDmGrid().initializeGrid(dmFind.getDmGrid().getPropertyAccess().code(), 1260, 183, 1);
        dmFind.getHelper().addSort("Name", DmSortType.ASC);
        dmFind.getHelper().addSort("Currency", DmSortType.ASC);
    }
//</editor-fold>

    public CountryMaster_Dsg() {
        ini();
    }

    private void ini() {
        FlowPanel flw;

        DmClient.setStyle(vrtInnerForm, "100%", "100%", null, null, DmPosition.NONE, true);
        flwForm.setStyleName("dm-FlwForm");
        flwForm.setHeight(String.valueOf(dmFind.getGridHeight() + 26) + "px");
        vrtInnerForm.add(vl.add(topControl));
        iniFind();
        iniCurrency();
        flw = new FlowPanel();
        flw.setStyleName("dm-FlwWorkingArea");
        flw.add(workingArea());
        vrtInnerForm.add(flw);
        vrtInnerForm.setCellHeight(flw, "100%");
        userControl.addTextBlog(preparedByBlog, 100, false, true);
        userControl.addGap(100);
        userControl.addTextBlog(modifiedByBlog, 100, true, false);
        vrtInnerForm.add(userControl);

        flwForm.add(vrtInnerForm);
    }

    private FlowPanel workingArea() {
        FlowPanel flwTable, flwTr, flwTd;
        DmLabel lbl;

        flwTable = new FlowPanel();
        DmClient.setStyle(flwTable, "50%", "40px", null, null, DmPosition.CENTER, true);

        //Country Name
        flwTr = new FlowPanel();
        DmClient.setStyle(flwTr, "100%", null, "left", null, DmPosition.NONE, true);
        flwTd = new FlowPanel();
        DmClient.setStyle(flwTd, "35%", null, "left", null, DmPosition.NONE, false);
        lbl = new DmLabel("Country Name");
        flwTd.add(lbl);
        flwTr.add(flwTd);

        flwTd = new FlowPanel();
        DmClient.setStyle(flwTd, "65%", null, "left", null, DmPosition.NONE, false);
        txtCountryName.setMandatory(true);
        flwTd.add(vl.add(txtCountryName));
        txtCountryName.setMaxLength(25);
        flwTr.add(flwTd);
        flwTable.add(flwTr);

        //Currency Name
        flwTr = new FlowPanel();
        DmClient.setStyle(flwTr, "100%", null, "left", null, DmPosition.NONE, true);
        flwTd = new FlowPanel();
        DmClient.setStyle(flwTd, "35%", null, "left", null, DmPosition.NONE, false);
        lbl = new DmLabel("Currency");
        flwTd.add(lbl);
        flwTr.add(flwTd);

        flwTd = new FlowPanel();
        DmClient.setStyle(flwTd, "65%", null, "left", null, DmPosition.NONE, false);
//        txtHCurrency.setMandatory(true);
        flwTd.add(vl.add(txtHCurrency));
        flwTr.add(flwTd);
        flwTable.add(flwTr);

        return flwTable;
    }
}
