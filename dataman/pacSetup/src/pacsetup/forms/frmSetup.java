    private void startCommandsExecution() {
        try {
            List<AbstractCommand> commands = ((CommandTableModel) tblTasks.getModel()).getCommands();
            List<Future> lstFutures = new ArrayList<>();
            for (int i = 0; i < commands.size(); i++) {
                Future future = Functions.getCachedExecutors().submit(commands.get(i));
                lstFutures.add(future);
            }
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

    private void setTableModel() {
        try {
            String serverUrl = Functions.getConfigurationProperty("service_url") + "/dataman/dmToolkit/self/server/DmPACSetup_Srvlt";
            AbstractCommand command;
            CommandTableModel commandModel;
            
            command = new InstallFontsCommand(serverUrl, "installFonts", "Install Fonts");
            commandModel = new CommandTableModel(command);

            command = new InstallPACPlugin(serverUrl, "installPlugin", "Install PAC");
//            commandModel = new CommandTableModel(command);
            commandModel.getCommands().add(command);

            tblTasks.setModel(commandModel);
        } catch (Exception ex) {
            ex.printStackTrace();
        }
    }

